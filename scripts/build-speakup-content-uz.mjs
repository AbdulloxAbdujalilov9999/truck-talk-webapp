/* Builds speakup/shared/content-uz.js — Uzbek translations SpeakUp does not carry in curriculum.js itself:
 * the example sentences under each vocabulary word and the quiz questions (lessons, reviews and the Grammar Book).
 * (Word meanings, dialogues, titles and speaking prompts are already baked into curriculum.js as Uzbek.)
 *
 *   node scripts/build-speakup-content-uz.mjs
 *
 * Source: the hand-written Uzbek of the ORIGINAL 90 days in scripts/data/speakup-uz/ ("English prefix§Uzbek" entries,
 * so a misaligned entry is caught). It re-applies the same lesson merges as the 60-lesson curriculum (day map in
 * speakup/shared/progress-merge.js). Format = same as content-ru.js: window.TT_CONTENT.uz = { days, grammar }. */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { loadOld, loadUz, resolve } from "./check-speakup-uz.mjs";
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const { DAY_MAP } = createRequire(import.meta.url)("../speakup/shared/progress-merge.js");
const NEW = new Function(fs.readFileSync(path.join(root, "speakup/curriculum.js"), "utf8") + ";return CURRICULUM")();
const GRAMMAR = new Function(fs.readFileSync(path.join(root, "speakup/grammar.js"), "utf8") + ";return GRAMMAR")();
const OLD = loadOld(), { X, Q, GQ } = loadUz();

const problems = []; const qmap = new Map(); const seenFrom = new Map();
const addQ = (en, uz, where) => { if (qmap.has(en) && qmap.get(en) !== uz) problems.push(`question "${en}": "${seenFrom.get(en)}" says "${qmap.get(en)}", ${where} says "${uz}"`); else { qmap.set(en, uz); seenFrom.set(en, where); } };
const oldX = {}, oldQ = {};
for (const d of OLD) {
  if (d.rev) continue;
  const rx = resolve(`day ${d.d} X`, X[d.d], d.v.map((v) => v[2])); const rq = resolve(`day ${d.d} Q`, Q[d.d], d.qz.map((q) => q[0]));
  problems.push(...rx.problems, ...rq.problems); oldX[d.d] = rx.uz; oldQ[d.d] = rq.uz;
  d.qz.forEach((q, i) => addQ(q[0], rq.uz[i], `day ${d.d}`));
}
const gq = {};
for (const u of GRAMMAR) { const r = resolve(`grammar ${u.id} Q`, GQ[u.id], u.quiz.map((q) => q[0])); problems.push(...r.problems); gq[u.id] = r.uz; u.quiz.forEach((q, i) => addQ(q[0], r.uz[i], `grammar ${u.id}`)); }
if (Q.extra) { const eng = ["What is 'if I were you' used for?"]; const r = resolve("extra Q", Q.extra, eng); problems.push(...r.problems); addQ(eng[0], r.uz[0], "extra"); }

const days = {};
for (const nd of NEW) {
  const olds = DAY_MAP[nd.d]; const out = {};
  if (nd.rev) out.q = nd.qz.map((q) => { const u = qmap.get(q[0]); if (!u) problems.push(`day ${nd.d}: no Uzbek for question "${q[0]}"`); return u || ""; });
  else {
    out.x = olds.flatMap((o) => oldX[o]); out.q = olds.flatMap((o) => oldQ[o]);
    if (out.x.length !== nd.v.length) problems.push(`day ${nd.d}: x ${out.x.length} vs ${nd.v.length}`);
    if (out.q.length !== nd.qz.length) problems.push(`day ${nd.d}: q ${out.q.length} vs ${nd.qz.length}`);
  }
  days[nd.d] = out;
}
if (problems.length) { console.error(problems.length + " problem(s):\n  " + problems.slice(0, 40).join("\n  ")); process.exit(1); }
const j = (x) => JSON.stringify(x);
let js = `/* SpeakUp — Uzbek translations of the example sentences and quiz questions (lessons, reviews, Grammar Book).
 * GENERATED by scripts/build-speakup-content-uz.mjs from scripts/data/speakup-uz/ — do not edit by hand.
 * Loaded on demand by app.js (Uzbek is the default language); lists are index-matched to curriculum.js / grammar.js. */
(function(){
var R={},GR={};
`;
for (const nd of NEW) { const d = days[nd.d]; js += `R[${nd.d}]={${[d.x ? `x:${j(d.x)}` : null, `q:${j(d.q)}`].filter(Boolean).join(",\n")}};\n`; }
for (const u of GRAMMAR) js += `GR[${j(u.id)}]={q:${j(gq[u.id])}};\n`;
js += `
window.TT_CONTENT = window.TT_CONTENT || {};
window.TT_CONTENT.uz = { days: R, grammar: GR };
})();
`;
fs.writeFileSync(path.join(root, "speakup/shared/content-uz.js"), js);
console.log(`speakup/shared/content-uz.js: ${NEW.length} days, ${GRAMMAR.length} grammar quizzes, ${qmap.size} distinct questions, ${(js.length / 1024).toFixed(0)} KB`);
